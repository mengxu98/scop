test_that("LINGER metadata follows selected cell identities", {
  counts <- matrix(c(2L, 3L, 4L, 5L, 6L, 7L), nrow = 2L,
    dimnames = list(c("G1", "G2"), c("c1", "c2", "c3")))
  object <- SeuratObject::CreateSeuratObject(methods::as(counts, "dgCMatrix"))
  object$sample <- c("s1", "s1", "s2")
  object$label <- c("B", "T", "Mono")
  input <- list(object = object, cells = c("c3", "c1"), group = "all")
  config <- list(method_args = list(sample.by = "sample", label.by = "label"))
  metadata <- grn_linger_metadata(input, config)
  expect_identical(metadata$cell_id, c("c3", "c1"))
  expect_identical(metadata$sample, c("s2", "s1"))
  expect_identical(metadata$label, c("Mono", "B"))
  config$method_args$sample.by <- "missing"
  expect_error(grn_linger_metadata(input, config), "existing metadata columns")
  config$method_args <- list()
  metadata <- grn_linger_metadata(input, config)
  expect_identical(metadata$sample, rep("sample1", 2L))
  expect_identical(metadata$label, rep("all", 2L))
  input$cells <- c("c1", "missing")
  expect_error(grn_linger_metadata(input, config), "missing from Seurat metadata")
})

test_that("LINGER checks counts at the modality boundary", {
  counts <- matrix(1:6, nrow = 2L,
    dimnames = list(c("01", "1"), c("c1", "c2", "c3")))
  object <- SeuratObject::CreateSeuratObject(methods::as(counts, "dgCMatrix"))
  actual <- grn_linger_counts(object, "RNA", "counts", c("c3", "c1"))
  expect_identical(rownames(actual), c("01", "1"))
  expect_equal(as.matrix(actual), counts[, c("c3", "c1")])
  expect_error(grn_linger_counts(object, "RNA", "data", "c1"), "count layers")
  expect_error(grn_linger_counts(object, "ATAC", "counts", "c1"), "selected RNA and ATAC assays")
  expect_error(grn_linger_counts(object, "RNA", "counts", "missing"), "match the selected group")
  object[["ATAC"]] <- SeuratObject::CreateAssayObject(methods::as(counts, "dgCMatrix"))
  expect_equal(as.matrix(grn_linger_counts(object, "ATAC", "counts", c("c3", "c1"))), counts[, c("c3", "c1")])
  object <- SeuratObject::SetAssayData(object, assay = "RNA", layer = "counts", new.data = counts / 2)
  expect_error(grn_linger_counts(object, "RNA", "counts", "c1"), "integer RNA and ATAC counts")
  object[["RNA"]] <- SeuratObject::CreateAssay5Object(counts = methods::as(counts, "dgCMatrix"))
  object[["RNA"]] <- split(object[["RNA"]], f = c("A", "B", "A"))
  expect_error(grn_linger_counts(object, "RNA", "counts", "c1"), "JoinLayers")
})

test_that("LINGER rejects unsupported inputs before starting a process", {
  input <- list(object = matrix(1, 2L, 2L), input_mode = "rna")
  expect_error(grn_run_linger(input, list()), "paired multiome Seurat")
  object <- SeuratObject::CreateSeuratObject(methods::as(matrix(1L, 2L, 3L,
    dimnames = list(c("G1", "G2"), c("c1", "c2", "c3"))), "dgCMatrix"))
  input <- list(object = object, input_mode = "multiome", cells = colnames(object))
  expect_error(grn_run_linger(input, list(method_args = list(resume_dir = tempfile()))), "completed prepare checkpoint directory")
  resume <- tempfile("resume-test-")
  dir.create(resume)
  on.exit(unlink(resume, recursive = TRUE), add = TRUE)
  expect_error(grn_run_linger(input, list(method_args = list(resume_dir = resume), groups = list(A = "c1", B = "c2"))), "exactly one selected group")
  expect_error(grn_run_linger(input, list(method_args = list(genome = "mm10"))), "hg19.*hg38")
  expect_error(grn_run_linger(input, list(method_args = list(genome = c("hg19", "hg38")))), "hg19.*hg38")
  expect_error(grn_run_linger(input, list(method_args = list(activation = "bad"))), "activation")
  expect_error(grn_run_linger(input, list(method_args = list(activation = NA_character_))), "activation")
  expect_error(grn_run_linger(input, list(method_args = list(patch_missing_keys = "yes"))), "TRUE or FALSE")
  expect_error(grn_run_linger(input, list(method_args = list(min_cells = -1))), "nonnegative integers")
  expect_error(grn_run_linger(input, list(method_args = list(), resources = list())), "bulk_reference")
})

test_that("LINGER reference selection hashes only the complete used file set", {
  source_root <- testthat::test_path("..", "..")
  if (file.exists(file.path(source_root, "inst", "grn", "linger", "reference-files.json"))) withr::local_dir(source_root)
  counts <- methods::as(matrix(1L, 2L, 3L,
    dimnames = list(c("G1", "G2"), c("c1", "c2", "c3"))), "dgCMatrix")
  object <- SeuratObject::CreateSeuratObject(counts)
  peaks <- counts
  rownames(peaks) <- c("chr19-10-20", "chr19:30-40")
  object[["ATAC"]] <- SeuratObject::CreateAssayObject(peaks)
  input <- list(object = object)
  directory <- tempfile("linger-reference-")
  dir.create(directory)
  on.exit(unlink(directory, recursive = TRUE), add = TRUE)
  config <- list(atac_assay = "ATAC", method_args = list(genome = "hg38"), resources = list(bulk_reference = directory))
  selected <- grn_linger_reference_files(input, config)
  expect_error(grn_linger_reference_files(list(object = counts), config), "paired Seurat object")
  expect_error(grn_linger_reference_files(input, modifyList(config, list(atac_assay = "missing"))), "selected ATAC assay")
  expect_length(selected$files, 15L)
  expect_identical(selected$chromosomes, "chr19")
  expect_true("hg38_hg19_pair.bed" %in% selected$files)
  expect_false("all_models_chr1.pt" %in% selected$files)
  for (file in selected$files) writeLines("A", file.path(directory, file))
  first <- grn_linger_resource_identity(input, config)
  expect_identical(names(first$bulk_reference[[1L]]$files), selected$files)
  used <- file.path(directory, "all_models_chr19.pt")
  original_time <- file.info(used)$mtime
  writeLines("B", used)
  Sys.setFileTime(used, original_time)
  expect_identical(file.info(used)$mtime, original_time)
  changed <- grn_linger_resource_identity(input, config)
  expect_false(identical(first, changed))
  unused <- file.path(directory, "all_models_chr1.pt")
  writeLines("unused", unused)
  expect_identical(grn_linger_resource_identity(input, config), changed)
  writeLines("changed unused", unused)
  expect_identical(grn_linger_resource_identity(input, config), changed)
  unlink(used)
  expect_error(grn_linger_resource_identity(input, config), "all_models_chr19.pt")
  config$method_args$genome <- "hg19"
  expect_true("hg19_hg38_pair.bed" %in% grn_linger_reference_files(input, config)$files)
})

test_that("LINGER prepare identity skips malformed distribution metadata", {
  python <- Sys.which("python3")
  skip_if(!nzchar(python), "Python 3 is unavailable")
  source_root <- testthat::test_path("..", "..")
  runner <- file.path(source_root, "inst", "grn", "linger", "run.py")
  if (!file.exists(runner)) runner <- system.file("grn", "linger", "run.py", package = "scop", mustWork = TRUE)
  probe <- testthat::test_path("python", "grn_linger_prepare_identity.py")
  output <- suppressWarnings(system2(python, c(shQuote(probe), shQuote(runner)), stdout = TRUE, stderr = TRUE))
  expect_null(attr(output, "status"), info = paste(output, collapse = "\n"))
  expect_true("LINGER_PREPARE_IDENTITY_METADATA_PASSED" %in% output)
})
