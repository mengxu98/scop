test_that("GRN resource identity detects content changes even with identical file metadata", {
  file <- withr::local_tempfile()
  writeLines("first", file)
  original_time <- file.info(file)$mtime
  before <- grn_resource_identity(file)
  writeLines("other", file)
  Sys.setFileTime(file, original_time)
  after <- grn_resource_identity(file)
  expect_false(identical(before, after))
  expect_identical(file.info(file)$mtime, original_time)
})

test_that("GRN directory resource identities include nested filenames and bytes", {
  directory <- withr::local_tempdir()
  dir.create(file.path(directory, "nested"))
  writeLines("reference", file.path(directory, "nested", "reference.tsv"))
  before <- grn_resource_identity(directory)
  expect_identical(names(before[[1L]]$files), "nested/reference.tsv")
  writeLines("model", file.path(directory, "weights.bin"))
  expect_false(identical(before, grn_resource_identity(directory)))
  expect_false(identical(grn_resource_identity(list(motif = c(a = 1, b = 2))), grn_resource_identity(list(motif = c(a = 2, b = 1)))))
})

test_that("SCENIC+ fingerprints include the final block of large references", {
  python <- Sys.which("python3")
  skip_if(!nzchar(python))
  directory <- withr::local_tempdir()
  ranking <- file.path(directory, "rankings.feather")
  scores <- file.path(directory, "scores.feather")
  writeLines("small reference", scores)
  change_byte <- function(byte) {
    handle <- file(ranking, if (file.exists(ranking)) "r+b" else "w+b")
    on.exit(close(handle))
    seek(handle, where = 64 * 1024^2, rw = "write")
    writeBin(as.raw(byte), handle)
  }
  change_byte(1L)
  config <- list(method = "scenicplus", work_dir = directory,
    resources = list(ranking_db = ranking, scores_db = scores), runtime = list(python = unname(python), timeout = 30))
  before <- grn_scenicplus_resource_identity(config)
  expect_identical(before, grn_scenicplus_resource_identity(config))
  expect_identical(before$ranking_db[[1L]]$algorithm, "sha256-tree-64m-v1")
  expect_identical(before$scores_db, grn_resource_identity(scores))
  original_time <- file.info(ranking)$mtime
  change_byte(2L)
  Sys.setFileTime(ranking, original_time)
  after <- grn_scenicplus_resource_identity(config)
  expect_false(identical(before$ranking_db, after$ranking_db))
  expect_identical(before$scores_db, after$scores_db)
})

test_that("multiome identity follows metadata and count inputs used by native methods", {
  skip_if_not_installed("Signac")
  counts <- Matrix::Matrix(matrix(seq_len(12L), nrow = 3L, dimnames = list(paste0("g", 1:3), paste0("c", 1:4))), sparse = TRUE)
  object <- SeuratObject::CreateSeuratObject(counts)
  object <- SeuratObject::SetAssayData(object, assay = "RNA", layer = "data", new.data = counts / 3)
  atac <- Matrix::Matrix(counts, sparse = TRUE)
  rownames(atac) <- c("chr1-1-20", "chr1-31-50", "chr1-61-80")
  object[["ATAC"]] <- Signac::CreateChromatinAssay(atac, min.cells = 0, min.features = 0)
  object <- SeuratObject::SetAssayData(object, assay = "ATAC", layer = "data", new.data = atac / 2)
  object$label <- c("one", "one", "two", "two")
  input <- list(object = object, expression = counts / 3, cells = colnames(object), input_mode = "multiome")
  config <- list(method = "multicsn", assay = "RNA", layer = "data", atac_assay = "ATAC", atac_layer = "data", method_args = list(preset = "timepoint"))
  before <- grn_input_identity(input, config)
  rna <- SeuratObject::LayerData(input$object, assay = "RNA", layer = "counts")
  rna[1L, 1L] <- rna[1L, 1L] + 1
  input$object <- SeuratObject::SetAssayData(input$object, assay = "RNA", layer = "counts", new.data = rna)
  expect_identical(SeuratObject::LayerData(input$object, assay = "RNA", layer = "data"), counts / 3)
  expect_false(identical(before, grn_input_identity(input, config)))
  before <- grn_input_identity(input, config)
  input$object$label <- unname(rev(input$object$label))
  expect_false(identical(before, grn_input_identity(input, config)))
  before <- grn_input_identity(input, config)
  atac <- SeuratObject::LayerData(input$object, assay = "ATAC", layer = "counts")
  atac[1L, 1L] <- atac[1L, 1L] + 1
  input$object <- SeuratObject::SetAssayData(input$object, assay = "ATAC", layer = "counts", new.data = atac)
  expect_false(identical(before, grn_input_identity(input, config)))
})

test_that("installed code identity ignores generated Python bytecode", {
  directory <- withr::local_tempdir()
  dir.create(file.path(directory, "grn"))
  dir.create(file.path(directory, "grn", "__pycache__"))
  writeLines("Package: scop", file.path(directory, "DESCRIPTION"))
  writeLines("print('scientific-code')", file.path(directory, "grn", "run.py"))
  before <- grn_package_code_identity(directory)
  writeLines("generated-bytecode", file.path(directory, "grn", "__pycache__", "run.pyc"))
  expect_identical(grn_package_code_identity(directory), before)
  writeLines("print('new-scientific-code')", file.path(directory, "grn", "run.py"))
  expect_false(identical(grn_package_code_identity(directory), before))
})
