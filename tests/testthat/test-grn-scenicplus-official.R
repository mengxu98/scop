test_that("official SCENIC+ validates all resources before starting a process", {
  input <- list(cells = c("01", "1"))
  config <- list(resources = list())
  expect_error(grn_run_scenicplus(input, config), "cistopic, gex, region_sets")
  expect_error(grn_scenicplus_check_resources(list()), "cistopic, gex, region_sets, ranking_db, scores_db, motif_annotation, genome_annotation, chromsizes", fixed = TRUE)
  directory <- tempfile("scenicplus-preflight-")
  dir.create(directory)
  on.exit(unlink(directory, recursive = TRUE), add = TRUE)
  required <- c("cistopic", "gex", "ranking_db", "scores_db", "motif_annotation", "genome_annotation", "chromsizes")
  resources <- stats::setNames(as.list(file.path(directory, required)), required)
  for (path in resources) writeLines("resource", path)
  resources$region_sets <- file.path(directory, "regions")
  dir.create(resources$region_sets)
  dir.create(file.path(resources$region_sets, "topics"))
  writeLines("chr1\t1\t10", file.path(resources$region_sets, "topics", "one.bed"))
  expect_error(grn_scenicplus_check_resources(resources), "at least two region sets")
  writeLines("chr1\t11\t20", file.path(resources$region_sets, "topics", "two.bed"))
  expect_setequal(grn_scenicplus_check_resources(resources), c(required, "region_sets"))
  unlink(resources$genome_annotation)
  expect_error(grn_scenicplus_check_resources(resources), "Missing SCENIC[+] resources: genome_annotation")
  writeLines("", resources$genome_annotation)
  resources$workflow <- directory
  expect_error(grn_scenicplus_check_resources(resources), "official Snakefile")
  file.create(file.path(directory, "Snakefile"), file.path(directory, "config.yaml"))
  expect_setequal(grn_scenicplus_check_resources(resources), c(required, "region_sets"))
})

test_that("official SCENIC+ requests preserve defaults and relative resume directories", {
  directory <- tempfile("scenicplus-request-")
  dir.create(directory)
  on.exit(unlink(directory, recursive = TRUE), add = TRUE)
  withr::local_dir(directory)
  required <- c("cistopic", "gex", "ranking_db", "scores_db", "motif_annotation", "genome_annotation", "chromsizes")
  resources <- stats::setNames(as.list(file.path(directory, required)), required)
  for (path in resources) writeLines("resource", path)
  resources$region_sets <- file.path(directory, "regions")
  dir.create(file.path(resources$region_sets, "topics"), recursive = TRUE)
  for (name in c("one.bed", "two.bed")) {
    writeLines("chr1\t1\t10", file.path(resources$region_sets, "topics", name))
  }
  cells <- c("01", "1")
  expression <- Matrix::Matrix(matrix(1:4, 2L, dimnames = list(c("G1", "G2"), cells)))
  input <- list(cells = cells, expression = expression, group = "all")
  config <- list(resources = resources, work_dir = "new", cores = 1L, seed = 42L,
    runtime = list(python = "python"), method_args = list())
  dir.create("checkpoint")
  testthat::local_mocked_bindings(runner_run_process = function(command, args, work_dir, ...) {
    request_path <- tail(args, 1L)
    request <- jsonlite::read_json(request_path)
    if (length(request$method_args)) {
      expect_identical(request$output_dir, normalizePath("checkpoint"))
    } else {
      expect_match(paste(readLines(request_path), collapse = "\n"), '"method_args": {}', fixed = TRUE)
      expect_identical(request$output_dir, file.path(normalizePath(config$work_dir), "official"))
    }
    expect_identical(unlist(request$cells), cells)
    stop("Request validated", call. = FALSE)
  }, .package = "scop")
  expect_error(grn_run_scenicplus(input, config), "Request validated", fixed = TRUE)
  config$method_args <- list(resume_dir = "checkpoint")
  expect_error(grn_run_scenicplus(input, config), "Request validated", fixed = TRUE)
})

test_that("official SCENIC+ retains separate evidence, identifiers and native modalities", {
  directory <- tempfile("scenicplus-native-")
  dir.create(directory)
  on.exit(unlink(directory, recursive = TRUE), add = TRUE)
  tables <- list(
    tf_gene = data.frame(TF = c("01", "1"), target = c("1", "01"), importance = c(2, 3), rho = c(-0.4, 0.7)),
    tf_region = data.frame(TF = "01", Region = "chr1:100-200", annotation_type = "direct", membership = 1L),
    region_gene = data.frame(region = "chr1:100-200", target = "1", importance = 4, rho = 0.6),
    direct = data.frame(TF = "01", Region = "chr1:100-200", Gene = "1", rho_R2G = 0.6, rho_TF2G = -0.4, importance_R2G = 4, is_extended = FALSE),
    extended = data.frame(TF = character(), Region = character(), Gene = character(), rho_R2G = numeric(), rho_TF2G = numeric(), importance_R2G = numeric(), is_extended = logical()),
    chains = data.frame(TF = "01", Region = "chr1:100-200", Gene = "1", rho_R2G = 0.6, rho_TF2G = -0.4, importance_R2G = 4, is_extended = FALSE)
  )
  for (name in names(tables)) utils::write.table(tables[[name]], file.path(directory, paste0(name, ".tsv")), sep = "\t", row.names = FALSE, quote = FALSE)
  auc <- data.frame(`01` = c(0.2, 0.5), check.names = FALSE, row.names = c("01", "1"))
  utils::write.table(auc, file.path(directory, "direct_gene_based_AUC.tsv"), sep = "\t", col.names = NA, quote = FALSE)
  jsonlite::write_json(list(`01` = c("1", "01")), file.path(directory, "gene_sets.json"), auto_unbox = FALSE)
  receipt <- list(status = "completed", cells = c("01", "1"), auc_files = "direct_gene_based_AUC.tsv", parameters = list(seed = 123), package_versions = list(scenicplus = "1.0a2"))
  jsonlite::write_json(receipt, file.path(directory, "execution.json"), auto_unbox = TRUE)
  result <- grn_scenicplus_group(directory, list(cells = c("01", "1")))
  expect_identical(result$native$tf_gene$TF, c("01", "1"))
  expect_identical(result$native$tf_gene$target, c("1", "01"))
  expect_identical(result$native$tf_gene$rho, c(-0.4, 0.7))
  expect_identical(result$native$region_gene$rho, 0.6)
  expect_identical(result$layer_specs$tf_gene$sign_column, "rho")
  expect_identical(result$layer_specs$region_gene$sign_column, "rho")
  expect_null(result$layer_specs$tf_region$sign_column)
  expect_identical(result$layer_specs$tf_region$sign_basis, "unknown")
  expect_identical(result$native$direct$is_extended, FALSE)
  expect_equal(nrow(result$native$extended), 0L)
  expect_identical(rownames(result$native$auc[[1L]]), c("01", "1"))
  expect_identical(result$implementation, "SCENIC+::official_snakemake")
  expect_identical(result$execution$status, "completed")
  selected <- grn_scenicplus_group(directory, list(cells = c("01", "1"), regulators = "01", targets = "1"))
  expect_identical(selected$layer_specs$tf_gene$rows, 1L)
  expect_equal(nrow(selected$native$tf_gene), 2L)
  expect_identical(selected$native$candidate_scope$selection, "postfit_view")
  wrapped <- structure(list(schema_version = "1.0", groups = list(all = selected)), class = c("GRNResult", "list"))
  expect_identical(GetGRN(wrapped)$source, "01")
  expect_identical(GetGRN(wrapped)$sign, -1L)
  expect_identical(GetGRN(wrapped, layer = "region_gene")$sign, 1L)
  expect_true(all(is.na(GetGRN(wrapped, layer = "tf_region")$sign)))
  expect_equal(nrow(GetGRN(wrapped, what = "native")$tf_gene), 2L)
  path <- file.path(directory, "result.rds")
  saveRDS(result, path)
  expect_identical(readRDS(path), result)
  receipt$status <- "failed"
  jsonlite::write_json(receipt, file.path(directory, "execution.json"), auto_unbox = TRUE)
  expect_error(grn_scenicplus_group(directory, list(cells = c("01", "1"))), "incomplete")
})
