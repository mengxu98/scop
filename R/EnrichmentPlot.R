#' @title Enrichment Plot
#'
#' @description
#' Generates various types of plots for enrichment (over-representation) analysis.
#'
#' @md
#' @inheritParams CellDimPlot
#' @inheritParams RunStandardWorkflow
#' @inheritParams scop-params
#' @param srt Deprecated alias for `object`; supply exactly one of the two. It
#' will be removed in scop 1.0.0.
#' @param object A Seurat object containing the results of RunDEtest and RunEnrichment.
#' If specified, enrichment results will be extracted from the `Seurat` object automatically.
#' If not specified, the `res` arguments must be provided.
#' @param group.by Grouping variable in the `Seurat` object.
#' This argument is only used if `object` is specified.
#' `NULL` (the default) selects the results that [RunEnrichment] stored for
#' custom gene sets or custom cell groups, which are keyed as `"custom"`.
#' @param test.use Test to be used in differential expression analysis.
#' This argument is only used if `object` is specified.
#' @param res Enrichment results generated by RunEnrichment function.
#' If provided, 'object', 'test.use' and 'group.by' are ignored.
#' @param db The database to use for enrichment plot.
#' @param plot_type The type of plot to generate. `"rank"` displays existing
#' enrichment results as ranked solid points, with one panel per group.
#' Options are `"bar"`, `"annotated_bar"`, `"dot"`, `"lollipop"`, `"network"`, `"enrichmap"`,
#' `"wordcloud"`, `"comparison"`, and `"rank"`.
#' "annotated_bar" draws horizontal bars with database bands, term labels,
#' hit-gene labels and optional Count dots.
#' @param rank_by Numeric enrichment column used for descending rank and the
#' y-axis in rank plots. Default is `"FoldEnrichment"`.
#' @param rank_nlabel Number of leading terms to label per rank panel (default 5).
#' @param rank_label_terms Optional term IDs or descriptions to label, or a named
#' list by group. Only displayed terms are labeled; this does not select terms.
#' @param rank_pt_size Positive increasing length-two point-size range for rank
#' plots (default `c(2, 5)`), mapped to `-log10(p.adjust)`.
#' @param rank_pt_alpha Background-point opacity in rank plots, from 0 to 1.
#' @param rank_label_size Text size for rank labels with black text and a white halo.
#' @param rank_shared_y Whether rank panels share a y-axis range. Default is
#' `FALSE`; compare numeric ticks when panels have independent ranges.
#' @param grid_major Whether to show major panel grid lines for rank plots (default TRUE).
#' @param split_by The splitting variable(s) for the plot.
#' Can be `"Database"`, `"Groups"`, or both.
#' Default is `c("Database", "Groups")` for plots.
#' For `"annotated_bar"`, the default is `"Groups"` (database bands within
#' each group). Including `"Database"` creates separate database panels;
#' groups are always kept in separate panels in this mode.
#' @param color_by The variable used for coloring.
#' Annotated bars use `"Database"`: each database receives one palette color.
#' As in the bar view of [GSEAPlot], significance controls opacity (0.4 to 1).
#' Bars, Count dots and hit-gene labels share the same color and opacity per term.
#' @param group_use The group(s) to be used for enrichment plot.
#' @param id_use List of IDs to be used to display specific terms in the enrichment plot.
#' Default value is `NULL`.
#' @param pvalueCutoff The p-value cutoff.
#' Only work when `padjustCutoff` is `NULL`.
#' @param padjustCutoff The p-adjusted cutoff.
#' @param score_col Optional numeric score column. When supplied, terms are
#' ranked and weighted by the absolute score and no p-value semantics are used.
#' This is intended for activity or importance results such as pathway scores.
#' @param scoreCutoff Optional minimum absolute score used with `score_col`.
#' @param score_label Legend label used with `score_col`.
#' @param topTerm The number of top terms to display.
#' Default is `6`, `100` for `"enrichmap"`, or `80` for `"rank"`.
#' Rank plots select the highest `rank_by` values after significance filtering.
#' @param compare_only_sig Whether to compare only significant terms.
#' @param topWord The number of top words to display for wordcloud.
#' @param word_type The type of words to display in wordcloud.
#' Options are `"term"` and `"feature"`.
#' @param word_size The size range for words in wordcloud.
#' @param words_excluded Words to be excluded from the wordcloud.
#' Default is `NULL`, which means that the built-in words ([words_excluded]) will be used.
#' @param network_layout The layout algorithm to use for network plot.
#' Options are `"fr"`, `"kk"`, `"random"`, `"circle"`, `"tree"`, `"grid"`, or other algorithm from `igraph` package.
#' @param network_labelsize The label size for network plot.
#' @param network_blendmode The blend mode for network plot.
#' @param network_layoutadjust Whether to adjust the layout of the network plot to avoid overlapping words.
#' @param network_adjscale The scale for adjusting network plot layout.
#' @param network_adjiter The number of iterations for adjusting network plot layout.
#' @param enrichmap_layout The layout algorithm to use for enrichmap plot.
#' Options are `"fr"`, `"kk"`, `"random"`, `"circle"`, `"tree"`, `"grid"`, or other algorithm from `igraph` package.
#' @param enrichmap_cluster The clustering algorithm to use for enrichmap plot.
#' Options are `"walktrap"`, `"fast_greedy"`, or other algorithm from `igraph` package.
#' @param enrichmap_label The label type for enrichmap plot.
#' Options are `"term"` and `"feature"`.
#' @param enrichmap_labelsize The label size for enrichmap plot.
#' @param enrichmap_nlabel The number of labels to display for each cluster in enrichmap plot.
#' @param enrlichmap_nlabel Deprecated. Please use \code{enrichmap_nlabel} instead.
#' @param enrichmap_show_keyword Whether to show the keyword of terms or features in enrichmap plot.
#' @param enrichmap_mark The mark shape for enrichmap plot.
#' Options are `"ellipse"` and `"hull"`.
#' @param enrichmap_expand The expansion factor for enrichmap plot.
#' @param character_width The maximum width of character of descriptions.
#' @param show_genes Logical; display hit genes below each annotated bar label.
#' Genes are taken from `geneID` as stored by [RunEnrichment]; no ID conversion
#' is performed. Missing gene strings are displayed as blank labels.
#' @param show_count Logical; display Count-sized dots beside annotated bars.
#' Missing counts are omitted. Use `legend.position = "none"` to hide the legend.
#' @param gene_width Positive integer (at least 4); maximum characters in an
#' annotated bar's comma-separated hit-gene label, including the ellipsis.
#' These three arguments apply only to `"annotated_bar"`.
#' @param row_step Positive numeric row spacing for annotated bars, at least
#' 0.8; defaults to 0.82 for a compact layout.
#' @param db_gap Non-negative numeric extra spacing between database bands
#' in annotated bars; defaults to 0.2.
#' @return A ggplot for one panel, a patchwork for combined panels, or a named
#' list of plots when `combine = FALSE`. Annotated bars select up to `topTerm`
#' terms per database and group, ordered by the selected p-value metric.
#' Database bands follow `db` order and panels share the same x-axis range.
#' Zero p-values are capped at `.Machine$double.xmin` before transformation;
#' missing p-values are omitted with a warning in this mode.
#' @param lineheight The line height for y-axis labels.
#' @param seed Random seed used for plot construction. The caller's RNG state
#' is restored on return, including errors.
#' @param palette Color palette name.
#' Defaults to `"Chinese"` for rank plots and `"Spectral"` otherwise.
#' Available palettes can be found in [thisplot::show_palettes].
#' @details Rank plots require one database and adjusted P values in `[0, 1]`.
#' They compare stored ORA results, not between-group differential significance.
#' `split_by` and `color_by` do not change rank panels: each group has one panel
#' and one color. Missing or nonfinite rank scores/adjusted P values are omitted
#' with a warning. Zero adjusted P values are capped at `.Machine$double.xmin`
#' only for the point-size transform. Groups without retained terms have empty
#' panels; if no term passes the existing enrichment filter, an error is raised.
#' @return A plot, or a list of plots when `combine = FALSE`. For `"rank"`,
#' the combined result is a patchwork with an `enrichment_data` attribute
#' containing displayed terms, ranks, scores and label-selection flags; the
#' uncombined result is a named list of ggplots with these columns in plot data.
#'
#' @details
#' Annotated bars place term labels inside bars and hit genes underneath, with
#' rounded database bands. Term text switches between black and white for the displayed
#' fill. A thin contrasting outline keeps overflow text readable.
#' Colors map one-to-one to `db` in the requested order;
#' named `palcolor` values must cover all selected databases. Descriptions are
#' truncated to at most `character_width` characters, with shorter limits for
#' shorter bars. Actual text fit also depends on export dimensions and font size.
#'
#' @seealso [RunEnrichment]
#'
#' @export
#'
#' @examples
#' # Plot an existing ORA result without running enrichment again:
#' rank_result <- list(enrichment = data.frame(
#'   ID = paste0("term", 1:6), Description = paste("Pathway", 1:6),
#'   Groups = rep(c("A", "B"), each = 3), Database = "custom",
#'   p.adjust = c(0.001, 0.01, 0.02, 0.002, 0.01, 0.03),
#'   FoldEnrichment = c(8, 5, 3, 7, 4, 2)
#' ))
#' EnrichmentPlot(
#'   res = rank_result, db = "custom", plot_type = "rank",
#'   rank_pt_size = c(2, 5), rank_nlabel = 2, ncol = 2
#' )
#'
#' # Constructed results illustrating the annotated layout (not biological data).
#' annotated_res <- list(enrichment = data.frame(
#'   ID = c("term1", "term2"), Description = c("Response process", "Cell component"),
#'   Database = c("GO_BP", "GO_CC"), Groups = "Example",
#'   p.adjust = c(0.001, 0.01), geneID = c("GeneA/GeneB", "GeneC/GeneD"), Count = 2
#' ))
#' EnrichmentPlot(res = annotated_res, db = "GO", plot_type = "annotated_bar")
#'
#' data(pancreas_sub)
#' pancreas_sub <- RunStandardWorkflow(pancreas_sub)
#' pancreas_sub <- RunDEtest(
#'   pancreas_sub,
#'   group.by = "CellType"
#' )
#'
#' pancreas_sub <- RunEnrichment(
#'   pancreas_sub,
#'   db = c("GO_BP", "GO_CC"),
#'   group.by = "CellType",
#'   species = "Mus_musculus"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   plot_type = "bar"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   plot_type = "bar",
#'   color_by = "Groups",
#'   ncol = 2
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   plot_type = "bar",
#'   id_use = list(
#'     "Ductal" = c(
#'       "GO:0002181", "GO:0045787",
#'       "GO:0006260", "GO:0050679"
#'     ),
#'     "Ngn3-low-EP" = c(
#'       "GO:0050678", "GO:0051101",
#'       "GO:0072091", "GO:0006631"
#'     ),
#'     "Ngn3-high-EP" = c(
#'       "GO:0035270", "GO:0030325",
#'       "GO:0008637", "GO:0030856"
#'     ),
#'     "Pre-endocrine" = c(
#'       "GO:0090276", "GO:0031018",
#'       "GO:0030073", "GO:1903532"
#'     )
#'   )
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   topTerm = 3,
#'   plot_type = "comparison"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   topTerm = 3,
#'   plot_type = "comparison",
#'   compare_only_sig = TRUE
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = c("Ductal", "Endocrine"),
#'   plot_type = "comparison"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = c("GO_BP", "GO_CC"),
#'   group.by = "CellType",
#'   group_use = c("Ductal", "Endocrine"),
#'   plot_type = "bar",
#'   split_by = "Groups"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = c("GO_BP", "GO_CC"),
#'   group.by = "CellType",
#'   group_use = c("Ductal", "Endocrine"),
#'   plot_type = "bar",
#'   split_by = "Database",
#'   color_by = "Groups"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = c("GO_BP", "GO_CC"),
#'   group.by = "CellType",
#'   group_use = c("Ductal", "Endocrine"),
#'   plot_type = "bar",
#'   split_by = c("Database", "Groups")
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = c("GO_BP", "GO_CC"),
#'   group.by = "CellType",
#'   plot_type = "bar",
#'   split_by = "Database",
#'   color_by = "Groups",
#'   palette = "Set1"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   plot_type = "dot",
#'   palette = "GdRd"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   plot_type = "lollipop",
#'   palette = "GdRd"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   plot_type = "wordcloud"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   plot_type = "wordcloud",
#'   word_type = "feature"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   plot_type = "network"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   plot_type = "network",
#'   id_use = c(
#'     "GO:0050678",
#'     "GO:0035270",
#'     "GO:0090276",
#'     "GO:0030073"
#'   )
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   plot_type = "network",
#'   network_layoutadjust = FALSE
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   plot_type = "network",
#'   topTerm = 4,
#'   network_blendmode = "average",
#'   theme_use = "theme_blank",
#'   theme_args = list(add_coord = FALSE)
#' ) |> thisplot::panel_fix(height = 5)
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   plot_type = "enrichmap"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   plot_type = "enrichmap",
#'   enrichmap_expand = c(2, 1)
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   plot_type = "enrichmap",
#'   enrichmap_show_keyword = TRUE,
#'   character_width = 10
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = "GO_BP",
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   plot_type = "enrichmap",
#'   topTerm = 200,
#'   enrichmap_mark = "hull",
#'   enrichmap_label = "feature",
#'   enrichmap_nlabel = 3,
#'   character_width = 10,
#'   theme_use = "theme_blank",
#'   theme_args = list(add_coord = FALSE)
#' ) |> thisplot::panel_fix(height = 4)
#'
#' pancreas_sub <- RunEnrichment(
#'   pancreas_sub,
#'   db = c("MP", "DO"),
#'   group.by = "CellType",
#'   convert_species = TRUE,
#'   species = "Mus_musculus"
#' )
#'
#' EnrichmentPlot(
#'   pancreas_sub,
#'   db = c("MP", "DO"),
#'   group.by = "CellType",
#'   group_use = "Ductal",
#'   ncol = 1
#' )
EnrichmentPlot <- function(
  object = NULL,
  db = "GO_BP",
  group.by = NULL,
  test.use = "wilcox",
  res = NULL,
  plot_type = c("bar", "annotated_bar", "dot", "lollipop", "network", "enrichmap", "wordcloud", "comparison", "rank"),
  split_by = c("Database", "Groups"),
  color_by = "Database",
  group_use = NULL,
  id_use = NULL,
  pvalueCutoff = NULL,
  padjustCutoff = 0.05,
  score_col = NULL,
  scoreCutoff = NULL,
  score_label = "Score",
  topTerm = ifelse(plot_type == "enrichmap", 100, ifelse(plot_type == "rank", 80, 6)),
  compare_only_sig = FALSE,
  topWord = 100,
  word_type = c("term", "feature"),
  word_size = c(2, 8),
  words_excluded = NULL,
  network_layout = "fr",
  network_labelsize = 5,
  network_blendmode = "blend",
  network_layoutadjust = TRUE,
  network_adjscale = 60,
  network_adjiter = 100,
  enrichmap_layout = "fr",
  enrichmap_cluster = "fast_greedy",
  enrichmap_label = c("term", "feature"),
  enrichmap_labelsize = 5,
  enrichmap_nlabel = 4,
  enrlichmap_nlabel = NULL,
  enrichmap_show_keyword = FALSE,
  enrichmap_mark = c("ellipse", "hull"),
  enrichmap_expand = c(0.5, 0.5),
  character_width = if (plot_type == "rank") 26 else 50,
  lineheight = 0.7,
  palette = if (plot_type == "rank") "Chinese" else "Spectral",
  palcolor = NULL,
  aspect.ratio = 1,
  legend.position = "right",
  legend.direction = "vertical",
  theme_use = "theme_scop",
  theme_args = list(),
  combine = TRUE,
  nrow = NULL,
  ncol = NULL,
  byrow = TRUE,
  seed = 11,
  verbose = TRUE,
  srt = NULL,
  rank_by = "FoldEnrichment",
  rank_nlabel = 5,
  rank_label_terms = NULL,
  rank_pt_size = c(2, 5),
  rank_pt_alpha = 0.23,
  rank_label_size = 3.2,
  grid_major = TRUE,
  rank_shared_y = FALSE,
  show_genes = TRUE,
  show_count = TRUE,
  gene_width = 70,
  row_step = 0.82,
  db_gap = 0.2
) {
  srt <- resolve_deprecated_srt(object, srt, missing(object))
  check_r("withr", verbose = FALSE)
  withr::local_preserve_seed()
  set.seed(seed)
  if (!is.null(enrlichmap_nlabel)) {
    enrichmap_nlabel <- enrlichmap_nlabel
  }
  plot_type <- match.arg(plot_type)
  if (plot_type == "annotated_bar") {
    if (!is.numeric(row_step) || length(row_step) != 1L || !is.finite(row_step) || row_step < 0.8) {
      log_message("{.arg row_step} must be a finite number of at least 0.8", message_type = "error")
    }
    if (!is.numeric(db_gap) || length(db_gap) != 1L || !is.finite(db_gap) || db_gap < 0) {
      log_message("{.arg db_gap} must be a finite non-negative number", message_type = "error")
    }
    if (missing(split_by)) split_by <- "Groups"
    split_by <- unique(c(split_by, "Groups"))
    for (flag in list(show_genes = show_genes, show_count = show_count)) {
      if (!is.logical(flag) || length(flag) != 1L || is.na(flag)) {
        log_message("{.arg show_genes} and {.arg show_count} must be TRUE or FALSE", message_type = "error")
      }
    }
    for (width in list(character_width, gene_width)) {
      if (!is.numeric(width) || length(width) != 1L || !is.finite(width) || width < 4 || width != floor(width)) {
        log_message("{.arg character_width} and {.arg gene_width} must be integers of at least 4", message_type = "error")
      }
    }
    if (!is.numeric(topTerm) || length(topTerm) != 1L || is.na(topTerm) || topTerm < 1 || (is.finite(topTerm) && topTerm != floor(topTerm))) {
      log_message("{.arg topTerm} must be a positive integer or Inf", message_type = "error")
    }
  }
  word_type <- match.arg(word_type)
  enrichmap_label <- match.arg(enrichmap_label)
  enrichmap_mark <- match.arg(enrichmap_mark)
  words_excluded <- words_excluded %||% scop::words_excluded
  score_mode <- !is.null(score_col)
  if (
    score_mode &&
      !plot_type %in% c("network", "enrichmap", "wordcloud")
  ) {
    log_message(
      paste0(
        "Score-based {.val bar}, {.val dot}, and {.val comparison} plots are ",
        "handled by {.fn thisplot::StatPlot} with {.arg stat_type = 'value'}."
      ),
      message_type = "error"
    )
  }

  if (any(!split_by %in% c("Database", "Groups"))) {
    log_message(
      "'split_by' must be either 'Database', 'Groups', or both of them",
      message_type = "error"
    )
  }
  if (plot_type %in% c("network", "enrichmap") && length(split_by) == 1) {
    log_message(
      "When 'plot_type' is 'network' or 'enrichmap', the 'split_by' parameter does not take effect.",
      message_type = "warning",
      verbose = verbose
    )
    split_by <- c("Database", "Groups")
  }

  if (is.null(res)) {
    if (is.null(srt)) {
      log_message(
        "Either {.arg object} or {.arg res} must be provided",
        message_type = "error"
      )
    }
    layer <- paste("Enrichment", group.by %||% "custom", test.use, sep = "_")
    if (!layer %in% names(srt@tools)) {
      available <- grep("^Enrichment", names(srt@tools), value = TRUE)
      if (length(available) == 0) {
        log_message(
          "No enrichment result found. You may perform {.fn RunEnrichment} first",
          message_type = "error"
        )
      }
      log_message(
        "No enrichment result {.val {layer}} found in {.code srt@tools}. ",
        "Available results: {.val {available}}. Set {.arg group.by} and {.arg test.use} ",
        "to match the {.fn RunEnrichment} call; custom gene sets and custom cell groups ",
        "are stored under {.arg group.by} {.val custom}.",
        message_type = "error"
      )
    }
    enrichment <- srt@tools[[layer]][["enrichment"]]
  } else {
    enrichment <- res[["enrichment"]]
  }

  if (!score_mode && is.null(pvalueCutoff) && is.null(padjustCutoff)) {
    log_message(
      "One of 'pvalueCutoff' or 'padjustCutoff' must be specified",
      message_type = "error"
    )
  }
  db <- resolve_enrichment_plot_db(db = db, enrichment = enrichment)
  if (!is.factor(enrichment["Groups"])) {
    enrichment[["Groups"]] <- factor(
      enrichment[["Groups"]],
      levels = unique(enrichment[["Groups"]])
    )
  }
  if (!is.factor(enrichment[["Database"]])) {
    enrichment[["Database"]] <- factor(
      enrichment[["Database"]],
      levels = unique(enrichment[["Database"]])
    )
  }
  if (!is.null(group_use)) {
    enrichment <- filter_enrichment_plot_groups(
      enrichment = enrichment,
      group_use = group_use
    )
  }
  if (length(id_use) > 0) {
    topTerm <- Inf
    if (is.list(id_use)) {
      if (is.null(names(id_use))) {
        log_message(
          "'id_use' must be named when it is a list",
          message_type = "error"
        )
      }
      id_use_names <- names(id_use)
      available_groups <- as.character(enrichment[["Groups"]])
      if (!all(id_use_names %in% available_groups)) {
        group_roots <- sub("::.*$", "", available_groups)
        root_map <- stats::setNames(available_groups, group_roots)
        remap <- !id_use_names %in% available_groups & id_use_names %in% names(root_map)
        id_use_names[remap] <- unname(root_map[id_use_names[remap]])
        names(id_use) <- id_use_names
      }
    }
    enrichment <- filter_enrichment_plot_ids(enrichment, id_use)
  }

